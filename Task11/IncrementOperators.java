class IncrementOperators 
{
	public static void main(String ary [])
	{
		int x = 10;
		System.out.println(x);
		
		x = x + 1 ;
		System.out.println(x);
		
		x += 1;
		System.out.println(x);
		
		x++;
		System.out.println(x);
		
		++x;
		System.out.println(x);
		
		System.out.println(++x);
		System.out.println(x++);
		System.out.println(x);
	}
} 